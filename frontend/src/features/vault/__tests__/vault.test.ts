import { parse } from "graphql";
import { MemoryVaultFs } from "../fs";
import { parseIdeaFile, serializeIdeaFile } from "../format";
import { VaultStore } from "../store";
import { CLOUD_SYNC_OFF, executeOnVault } from "../execute";
import { GET_IDEAS, GET_IDEA_CORE, GET_IDEA_DOCUMENTS, GET_PROFILE, UPDATE_IDEA, CREATE_IDEA, DELETE_IDEA } from "features/core/apollo/queries";
import { htmlToMarkdown, markdownToHtml } from "../convert";

const run = (store: VaultStore, doc: unknown, variables: Record<string, unknown> = {}) =>
  executeOnVault(store, doc as never, variables);

describe("idea files", () => {
  it("round-trips frontmatter, title and body, keeping keys Manifest doesn't use", () => {
    const text = [
      "---",
      "manifest_id: abc-123",
      "type: idea",
      "created: 2026-11-19T10:00:00.000Z",
      "published: false",
      "skills: [Embedded Systems, \"Sales, B2B\"]",
      "tags:",
      "  - startup",
      "---",
      "# TideLine",
      "",
      "Coastal streets flood **block by block**.",
    ].join("\n");
    const file = parseIdeaFile(text, "fallback");
    expect(file).toMatchObject({
      id: "abc-123",
      title: "TideLine",
      skills: ["Embedded Systems", "Sales, B2B"],
      body: "Coastal streets flood **block by block**.",
    });
    expect(file.extra).toEqual(["tags:", "  - startup"]);
    const again = parseIdeaFile(serializeIdeaFile(file), "fallback");
    expect(again).toMatchObject({ id: "abc-123", title: "TideLine", body: file.body, extra: file.extra });
  });

  it("reads a note written in another app (no frontmatter) and an account export", () => {
    expect(parseIdeaFile("Just a thought about bikes.", "Bike idea")).toMatchObject({
      id: null,
      title: "Bike idea",
      body: "Just a thought about bikes.",
    });
    const exported = [
      "---",
      "manifest_id: x1",
      "type: idea",
      "---",
      "<!-- manifest:begin — generated by Manifest; edits inside this block are replaced on the next sync -->",
      "# Sensor Rent",
      "",
      "Rent sensors to insurers. ^p1",
      "",
      "## Documents",
      "- stuff",
      "<!-- manifest:end -->",
      "",
      "## My notes",
      "Call the insurer.",
    ].join("\n");
    expect(parseIdeaFile(exported, "x")).toMatchObject({
      id: "x1",
      title: "Sensor Rent",
      body: "Rent sensors to insurers.",
      tail: "## My notes\nCall the insurer.",
    });
  });

  it("converts the editor's HTML to Markdown and back", () => {
    const html = "<h2>Problem</h2><p>Nurses <strong>skip</strong> meals and <s>sleep</s>.</p><ul><li><p>one</p></li><li><p>two</p></li></ul>";
    const md = htmlToMarkdown(html);
    expect(md).toBe("## Problem\n\nNurses **skip** meals and ~~sleep~~.\n\n- one\n- two");
    expect(markdownToHtml(md)).toContain("<strong>skip</strong>");
    expect(htmlToMarkdown("<p></p>")).toBe("");
  });
});

describe("a folder of ideas answers the app's GraphQL", () => {
  it("lists, opens, creates, edits, renames and deletes ideas as files", async () => {
    const fs = new MemoryVaultFs();
    await fs.write("Manifest/Ideas/Written in Obsidian.md", "# Bike lanes\n\nPaint them green.");
    const store = new VaultStore(fs);

    const profile = await run(store, GET_PROFILE);
    expect(profile.data).toEqual({ profile: { userId: "local", email: null, isGuest: false } });

    const list = await run(store, GET_IDEAS);
    const ideas = list.data!.ideas as { ideaId: string; title: string }[];
    expect(ideas.map((i) => i.title)).toEqual(["Bike lanes"]);
    // A note from another app gets an id written into its frontmatter.
    expect(await fs.read("Manifest/Ideas/Written in Obsidian.md")).toMatch(/^---\nmanifest_id: /);

    const created = await run(store, CREATE_IDEA, { title: "Night shift meals", description: "<p>Nurses skip meals.</p>" });
    const id = (created.data!.createIdea as { ideaId: string }).ideaId;
    expect(await fs.read("Manifest/Ideas/Night shift meals.md")).toContain("Nurses skip meals.");

    const core = await run(store, GET_IDEA_CORE, { ideaId: id });
    expect(core.data!.idea).toMatchObject({
      ideaId: id,
      userId: "local",
      title: "Night shift meals",
      description: "<p>Nurses skip meals.</p>",
      isPublished: false,
    });

    // The editor's exact HTML comes back after a save, so the note never reflows.
    const html = "<p>Nurses <em>skip</em> meals at 2am.</p>";
    const updated = await run(store, UPDATE_IDEA, { ideaId: id, title: "Meal plans for nurses", description: html });
    expect((updated.data!.updateIdea as { description: string }).description).toBe(html);
    expect(await fs.read("Manifest/Ideas/Night shift meals.md")).toBeNull();
    expect(await fs.read("Manifest/Ideas/Meal plans for nurses.md")).toContain("Nurses *skip* meals at 2am.");

    await fs.write("Manifest/Documents/Meal plans for nurses/Pitch Deck.md", "# Problem\nHungry nurses.");
    const docs = await run(store, GET_IDEA_DOCUMENTS, { ideaId: id });
    expect(docs.data!.idea).toMatchObject({ pitchDeck: "# Problem\nHungry nurses.", provisionalPatent: null });

    await run(store, DELETE_IDEA, { ideaId: id });
    expect(await fs.read("Manifest/Ideas/Meal plans for nurses.md")).toBeNull();
    const trashed = [...fs.files.keys()].filter((p) => p.startsWith("Manifest/.trash/"));
    expect(trashed.some((p) => p.endsWith(".md") && p.includes("Meal plans for nurses"))).toBe(true);
    expect(trashed.some((p) => p.endsWith("/Pitch Deck.md"))).toBe(true);
  });

  it("notices edits made on another computer", async () => {
    const fs = new MemoryVaultFs();
    const store = new VaultStore(fs);
    await store.create("Idea", "<p>First.</p>");
    expect(await store.refresh()).toBe(false);
    const [path] = fs.files.keys();
    await fs.write(path, (await fs.read(path))!.replace("First.", "Changed in iCloud."));
    expect(await store.refresh()).toBe(true);
    const [idea] = await store.list();
    expect((await store.get(idea.ideaId))!.description).toContain("Changed in iCloud.");
  });

  it("answers account-only features clearly instead of failing silently", async () => {
    const store = new VaultStore(new MemoryVaultFs());
    const share = await run(
      store,
      parse(`mutation { inviteCollaborator(input: {ideaId: "1", email: "a@b.c"}) { success } }`),
    );
    expect(share.errors?.[0].extensions?.code).toBe(CLOUD_SYNC_OFF);
    expect(share.errors?.[0].message).toMatch(/Cloud sync/);
    const versions = await run(store, parse(`query { ideaVersions(ideaId: "1") { versionId } account { userId } }`));
    expect(versions.data).toEqual({ ideaVersions: [], account: null });
  });
});
