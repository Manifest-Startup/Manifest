import React, { useMemo } from "react";
import { useMutation } from "@apollo/client/react";
import { useSafeQuery } from "features/common-ui/api/useSafeQuery";
import Button from "features/common-ui/Button";
import {
  GET_BMC_SECTIONS,
  REGENERATE_ALL_BMC_SECTIONS,
  REGENERATE_BMC_SECTION,
} from "features/core/apollo/queries";

/**
 * Per-section Business Model Canvas panel.
 *
 * Renders the nine canonical sections in canonical order. Each card
 * shows the section's current content (or a placeholder), a
 * "Regenerate" button, and a "needs review" badge when the agent
 * flagged it. A top-of-panel "Regenerate all" button triggers the
 * sequential orchestrator so later sections see earlier ones.
 *
 * The legacy monolithic BMC field on the Idea type still works for
 * older callers — this panel reads from the new
 * business_model_canvas_sections table via `bmcSections(ideaId)`.
 */

interface BmcSection {
  sectionName: string;
  content?: string | null;
  contentFormat?: string;
  needsUserReview?: boolean;
  generatedByRunId?: string | null;
  lastGeneratedAt?: string | null;
  lastUserEditAt?: string | null;
}

const SECTION_ORDER: { key: string; label: string }[] = [
  { key: "customer_segments", label: "Customer Segments" },
  { key: "value_propositions", label: "Value Propositions" },
  { key: "channels", label: "Channels" },
  { key: "customer_relationships", label: "Customer Relationships" },
  { key: "revenue_streams", label: "Revenue Streams" },
  { key: "key_resources", label: "Key Resources" },
  { key: "key_activities", label: "Key Activities" },
  { key: "key_partners", label: "Key Partners" },
  { key: "cost_structure", label: "Cost Structure" },
];

interface Props {
  ideaId: string;
}

const BmcSectionsPanel: React.FC<Props> = ({ ideaId }) => {
  const { data, loading, refetch } = useSafeQuery(GET_BMC_SECTIONS, {
    variables: { ideaId },
    skip: !ideaId,
    fetchPolicy: "cache-and-network",
  });

  const [regenerateOne, { loading: regenerating }] = useMutation(REGENERATE_BMC_SECTION);
  const [regenerateAll, { loading: regeneratingAll }] = useMutation(REGENERATE_ALL_BMC_SECTIONS);

  const sections: BmcSection[] = useMemo(() => {
    const incoming =
      (data as { bmcSections?: BmcSection[] } | undefined)?.bmcSections || [];
    const byName = new Map(incoming.map((s) => [s.sectionName, s]));
    return SECTION_ORDER.map(({ key }) => byName.get(key) || { sectionName: key });
  }, [data]);

  const onRegenerate = async (sectionName: string) => {
    await regenerateOne({ variables: { ideaId, sectionName } });
    await refetch();
  };
  const onRegenerateAll = async () => {
    await regenerateAll({ variables: { ideaId } });
    await refetch();
  };

  return (
    <section className="flex flex-col gap-4">
      <header className="flex items-baseline justify-between gap-3">
        <div>
          <h2 className="text-lg font-semibold tracking-tight text-neutral900 dark:text-white">
            Business Model Canvas — per-section agents
          </h2>
          <p className="text-xs text-neutral500 dark:text-gray400">
            Each section is generated by its own sub-agent. Regenerating one
            section keeps the others as context so the canvas stays consistent.
          </p>
        </div>
        <Button
          variant="secondary"
          onClick={onRegenerateAll}
          disabled={regeneratingAll || loading}
        >
          {regeneratingAll ? "Regenerating all…" : "Regenerate all 9"}
        </Button>
      </header>

      <div className="grid grid-cols-1 gap-4 md:grid-cols-2 lg:grid-cols-3">
        {sections.map((section) => {
          const labelEntry = SECTION_ORDER.find((s) => s.key === section.sectionName);
          const label = labelEntry?.label || section.sectionName;
          return (
            <BmcSectionCard
              key={section.sectionName}
              label={label}
              section={section}
              busy={regenerating || regeneratingAll}
              onRegenerate={() => onRegenerate(section.sectionName)}
            />
          );
        })}
      </div>
    </section>
  );
};

const BmcSectionCard: React.FC<{
  label: string;
  section: BmcSection;
  busy: boolean;
  onRegenerate: () => void;
}> = ({ label, section, busy, onRegenerate }) => {
  const empty = !section.content || !section.content.trim();
  return (
    <article className="flex flex-col gap-3 rounded-3xl border border-stone200 bg-white/80 p-4 shadow-soft dark:border-neutral700 dark:bg-neutral900/70">
      <header className="flex items-baseline justify-between gap-2">
        <h3 className="text-sm font-semibold text-neutral900 dark:text-white">{label}</h3>
        {section.needsUserReview ? (
          <span className="rounded-full bg-amber-100 px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wider text-amber-800 dark:bg-amber-900/30 dark:text-amber-300">
            Needs review
          </span>
        ) : null}
      </header>
      <div className="min-h-[80px] whitespace-pre-wrap text-xs leading-relaxed text-neutral700 dark:text-gray200">
        {empty ? (
          <span className="text-neutral400 dark:text-gray600">
            Not generated yet. Click <em>Regenerate</em> to draft this section.
          </span>
        ) : (
          section.content
        )}
      </div>
      <div className="flex items-center justify-between gap-2 text-[10px] text-neutral500 dark:text-gray400">
        <span>
          {section.lastGeneratedAt
            ? `Last generated ${new Date(section.lastGeneratedAt).toLocaleString()}`
            : "Never generated"}
        </span>
        <button
          type="button"
          onClick={onRegenerate}
          disabled={busy}
          className="rounded-full border border-stone200 px-3 py-1 text-[10px] font-semibold text-neutral700 hover:bg-stone50 disabled:opacity-50 dark:border-neutral700 dark:text-gray300 dark:hover:bg-neutral800"
        >
          {busy ? "…" : empty ? "Generate" : "Regenerate"}
        </button>
      </div>
    </article>
  );
};

export default BmcSectionsPanel;
