"""The plugin's local vault writer (agent-plugin/skills/manifest-vault/scripts/manifest_vault.py)."""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import pytest

SCRIPT = (
    Path(__file__).resolve().parents[2]
    / "agent-plugin/skills/manifest-vault/scripts/manifest_vault.py"
)
BEGIN = "<!-- manifest:begin — generated by Manifest; edits inside this block are replaced on the next sync -->"
END = "<!-- manifest:end -->"


@pytest.fixture
def mv():
    spec = importlib.util.spec_from_file_location("manifest_vault", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def generated(body: str, kind: str = "idea") -> str:
    return f'---\ntype: "{kind}"\n---\n{BEGIN}\n{body}\n{END}\n'


def export(tmp_path: Path, files: list[dict], at: str = "2026-11-18T04:00:00Z") -> Path:
    path = tmp_path / "export.json"
    path.write_text(
        json.dumps({"structuredContent": {"vaultExport": {"generatedAt": at, "files": files}}})
    )
    return path


def test_sync_creates_merges_and_never_clobbers(mv, tmp_path):
    vault = tmp_path / "vault"
    idea = "Manifest/Ideas/TideLine.md"
    src = export(tmp_path, [{"path": idea, "content": generated("v1")}])
    assert mv.main(["sync", "--vault", str(vault), str(src)]) == 0
    text = (vault / idea).read_text()
    assert "v1" in text and "## My notes" in text and (vault / "README.md").exists()
    (vault / idea).write_text(text + "My own thought about pricing.\n")

    src = export(tmp_path, [{"path": idea, "content": generated("v2")}])
    mv.main(["sync", "--vault", str(vault), str(src)])
    text = (vault / idea).read_text()
    assert "v2" in text and "v1" not in text and "My own thought about pricing." in text

    mine = vault / "Manifest/Ideas/Mine.md"
    mine.write_text("hand written, no markers")
    mv.main(
        [
            "sync",
            "--vault",
            str(vault),
            str(export(tmp_path, [{"path": "Manifest/Ideas/Mine.md", "content": generated("x")}])),
        ]
    )
    assert mine.read_text() == "hand written, no markers"
    assert (vault / "Manifest/Ideas/Mine (Manifest).md").exists()
    assert (
        json.loads((vault / ".manifest-sync.json").read_text())["last_sync"]
        == "2026-11-18T04:00:00Z"
    )


def test_sync_refuses_paths_outside_the_vault(mv, tmp_path):
    src = export(tmp_path, [{"path": "../escape.md", "content": generated("x")}])
    with pytest.raises(SystemExit):
        mv.main(["sync", "--vault", str(tmp_path / "vault"), str(src)])
    assert not (tmp_path / "escape.md").exists()


def test_notes_link_their_ideas(mv, tmp_path, capsys):
    vault = tmp_path / "vault"
    mv.main(
        [
            "note",
            "--vault",
            str(vault),
            "--title",
            "Pricing: per sensor?",
            "--idea",
            "TideLine",
            "--tag",
            "Pricing",
            "Cities pay per sensor.",
        ]
    )
    path = Path(capsys.readouterr().out.strip())
    text = path.read_text()
    assert path.parent == vault / "Notes" and path.name.endswith("Pricing per sensor.md")
    assert '  - "[[Manifest/Ideas/TideLine|TideLine]]"' in text and '  - "pricing"' in text
    assert "Cities pay per sensor." in text
    mv.main(["note", "--vault", str(vault), "--title", "Pricing: per sensor?", "again"])
    assert len(list((vault / "Notes").glob("*Pricing per sensor*.md"))) == 2, "never overwrites"


def test_folder_readmes_are_optional(mv, tmp_path):
    vault = tmp_path / "vault"
    src = export(tmp_path, [{"path": "Manifest/Ideas/A.md", "content": generated("a")}])
    mv.main(["sync", "--vault", str(vault), str(src)])
    assert not (vault / "Manifest/README.md").exists()
    mv.main(["sync", "--vault", str(tmp_path / "v2"), "--folder-readmes", str(src)])
    assert (tmp_path / "v2/Manifest/Ideas/README.md").exists()


def test_server_and_script_share_the_markers_and_names(mv):
    import sys

    sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "backend"))
    from app.services.ideas import vault

    assert vault.BEGIN.startswith(mv.BEGIN_PREFIX) and vault.END == mv.END
    for title in ("TideLine: a/b?", "  x  ", "[[weird]] #tag"):
        assert vault.safe_name(title) == mv.safe_name(title)


def test_sync_without_sign_in_says_how_and_status_works_offline(mv, tmp_path, monkeypatch, capsys):
    monkeypatch.setenv("MANIFEST_CONFIG", str(tmp_path / "none.json"))
    monkeypatch.delenv("MANIFEST_API_TOKEN", raising=False)
    vault = tmp_path / "vault"
    assert mv.main(["sync", "--vault", str(vault)]) == 2
    assert "manifest_vault.py login" in capsys.readouterr().err
    (vault / "Notes").mkdir(parents=True)
    (vault / "Notes/a.md").write_text("hi")
    assert mv.main(["status", "--vault", str(vault)]) == 0
    out = capsys.readouterr().out
    assert "not signed in" in out and "1 to upload" in out


def test_only_your_files_and_writing_sync(mv, tmp_path):
    vault = tmp_path / "vault"
    mv.main(
        [
            "sync",
            "--vault",
            str(vault),
            str(
                export(
                    tmp_path,
                    [
                        {"path": "Manifest/Ideas/A.md", "content": generated("# A")},
                    ],
                )
            ),
        ]
    )
    (vault / ".obsidian").mkdir(exist_ok=True)
    (vault / ".obsidian/workspace.md").write_text("private")
    (vault / "Notes/n.md").write_text("mine")
    (vault / "photo.png").write_bytes(b"x")
    found = mv.local_files(vault)
    assert found["Notes/n.md"] == ("file", "mine")
    assert found["Manifest/Ideas/A.md"][0] == "overlay"
    assert ".obsidian/workspace.md" not in found and "photo.png" not in found
    # The untouched "## My notes" scaffold isn't worth uploading.
    changed, _ = mv.pending_changes(vault, {})
    assert "Manifest/Ideas/A.md" not in changed and "Notes/n.md" in changed
