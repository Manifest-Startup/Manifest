def test_notes_link_their_ideas(mv, tmp_path, capsys):
    vault = tmp_path / "vault"
    mv.main(
        [
            "note",
            "--vault",
            str(vault),
            "--title",
            "Pricing: per sensor?",
            "--idea",
            "TideLine",
            "--tag",
            "Pricing",
            "Cities pay per sensor.",
        ]
    )
    path = Path(capsys.readouterr().out.strip())
    text = path.read_text()
    assert path.parent == vault / "Notes" and path.name.endswith("Pricing per sensor.md")
    assert '  - "[[Manifest/Ideas/TideLine|TideLine]]"' in text and '  - "pricing"' in text
    assert "Cities pay per sensor." in text
    mv.main(["note", "--vault", str(vault), "--title", "Pricing: per sensor?", "again"])
    assert len(list((vault / "Notes").glob("*Pricing per sensor*.md"))) == 2, "never overwrites"


