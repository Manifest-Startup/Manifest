-- Per-section Business Model Canvas content, owned by the
-- bmc_orchestrator_service. One row per (idea_id, section_name)
-- representing the latest generated content for that section,
-- with cost-tracked agent_run linkage.
--
-- Coexists with the legacy monolithic business_model_canvas_service.py
-- (which still backs the bulk-generated `business_model_canvas` field
-- on the Idea type). New per-section panels read from this table.
--
-- Owner: backend/app/services/bmc_orchestrator_service.py.
-- Architecture: docs/BMC_SUB_AGENTS.md.

CREATE TABLE IF NOT EXISTS public.business_model_canvas_sections (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    idea_id UUID NOT NULL REFERENCES public.ideas (idea_id) ON DELETE CASCADE,
    section_name TEXT NOT NULL,
    content TEXT,
    content_format TEXT NOT NULL DEFAULT 'markdown',
    -- True when the agent wants the user to review before downstream
    -- agents (pitch deck, PRD) consume the content.
    needs_user_review BOOLEAN NOT NULL DEFAULT FALSE,
    -- Latest agent_runs row that produced this content; nullable so a
    -- manual user edit can clear the link without dropping the row.
    generated_by_run_id UUID
        REFERENCES public.agent_runs (id) ON DELETE SET NULL,
    last_generated_at TIMESTAMPTZ,
    last_user_edit_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- (idea_id, section_name) is the natural key — one row per section
    -- per idea. UPSERT on regeneration.
    CONSTRAINT business_model_canvas_sections_uniq
        UNIQUE (idea_id, section_name)
);

CREATE INDEX IF NOT EXISTS idx_bmc_sections_idea
    ON public.business_model_canvas_sections (idea_id);
CREATE INDEX IF NOT EXISTS idx_bmc_sections_run
    ON public.business_model_canvas_sections (generated_by_run_id)
    WHERE generated_by_run_id IS NOT NULL;

COMMENT ON TABLE public.business_model_canvas_sections IS
    'Per-section BMC content. One row per (idea_id, section_name). Generated by bmc_orchestrator_service, one cost-tracked agent_run per regeneration.';
