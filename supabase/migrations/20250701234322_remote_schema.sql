CREATE OR REPLACE FUNCTION "public"."handle_new_user"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
begin
  insert into public.users (user_id, email, created_at, updated_at)
  values (new.id, new.email, now(), now());
  return new;
end;
$$;


