import json

from app.prompts import prompt_path
from app.services.canvas.channels import Channels
from app.services.canvas.cost_structure import CostStructure
from app.services.canvas.customer_relationships import CustomerRelationships
from app.services.canvas.customer_segments import CustomerSegments
from app.services.canvas.key_activities import KeyActivities
from app.services.canvas.key_partners import KeyPartners
from app.services.canvas.key_resources import KeyResources
from app.services.canvas.revenue_streams import RevenueStreams
from app.services.canvas.value_propositions import ValuePropositions
from app.utils.auto_property import AutoProperty
from app.utils.logger import logger


class BusinessModelCanvas:
    def _load_prompt_template(self):
        logger.info("[BMC] Loading prompt template from file")
        template_path = prompt_path("business_model_canvas.mcp.json")
        try:
            with open(template_path, encoding="utf-8") as f:
                data = json.load(f)
                logger.debug(f"[BMC] Successfully loaded prompt template from {template_path}")
                return data["prompt"]["system"], data["prompt"]["user"]
        except Exception as e:
            logger.error(f"[BMC] Failed to load prompt template: {str(e)}")
            raise

    def __init__(self, Model, *args, **kwargs):
        logger.info("[BMC] Initializing BusinessModelCanvas with all components")
        # Initialize all the components of the Business Model Canvas
        self._key_partners = KeyPartners()
        self._key_activities = KeyActivities()
        self._key_resources = KeyResources()
        self._value_propositions = ValuePropositions()
        self._customer_relationships = CustomerRelationships()
        self._channels = Channels()
        self._customer_segments = CustomerSegments()
        self._cost_structure = CostStructure()
        self._revenue_streams = RevenueStreams()
        self._model = Model
        self._summary = None  # Stores full BMC markdown summary
        logger.info("[BMC] Successfully initialized all nine BMC components")

    key_partners = AutoProperty("key_partners")
    key_activities = AutoProperty("key_activities")
    key_resources = AutoProperty("key_resources")
    value_propositions = AutoProperty("value_propositions")
    customer_relationships = AutoProperty("customer_relationships")
    channels = AutoProperty("channels")
    customer_segments = AutoProperty("customer_segments")
    cost_structure = AutoProperty("cost_structure")
    revenue_streams = AutoProperty("revenue_streams")

    # Getter and setter for summary (kept for custom logging)
    @property
    def summary(self):
        """
        Get the full Business Model Canvas summary as generated by the AI.
        """
        logger.debug("Accessing full BMC summary.")
        return self._summary

    @summary.setter
    def summary(self, value):
        """
        Set the full Business Model Canvas summary as returned by the AI.
        """
        logger.info("Setting full BMC summary.")
        self._summary = value

    def show(self):
        """
        Log all BMC components and their current values.
        """
        logger.info("[BMC] Displaying current state of all components")
        for attr in dir(self):
            if not attr.startswith("_") and not callable(getattr(self, attr)):
                component = getattr(self, attr)
                logger.info(f"[BMC] Component {attr.replace('_', ' ').title()}: {component}")

    def get_canvas(self):
        """
        Retrieve all components of the Business Model Canvas as a dictionary.
        """
        logger.info("[BMC] Retrieving complete canvas state")
        canvas = {
            "key_partners": self.key_partners,
            "key_activities": self.key_activities,
            "key_resources": self.key_resources,
            "value_propositions": self.value_propositions,
            "customer_relationships": self.customer_relationships,
            "channels": self.channels,
            "customer_segments": self.customer_segments,
            "cost_structure": self.cost_structure,
            "revenue_streams": self.revenue_streams,
        }
        logger.debug(f"[BMC] Canvas state: {json.dumps(canvas, indent=2)}")
        return canvas

    def get_cost_breakdown(self):
        """
        Retrieve the existing cost structure breakdown from the cost_structure component.
        Assumes cost_structure has already been generated and populated.
        """
        logger.info("[BMC] Fetching cost breakdown from cost_structure component")
        breakdown = {
            "cost_breakdown": getattr(self._cost_structure, "cost_breakdown", None),
            "total_estimate": getattr(self._cost_structure, "total_estimate", None),
            "currency": getattr(self._cost_structure, "currency", None),
        }
        logger.debug(f"[BMC] Cost breakdown: {json.dumps(breakdown, indent=2)}")
        return breakdown

    def update(self):
        """
        Update the Business Model Canvas using the current idea description.
        Triggers regeneration only when needed.
        """
        logger.info("[BMC] Checking if idea description is available for update")
        current_description = self._model.idea.description if hasattr(self._model, "idea") else None

        if current_description and current_description.strip():
            logger.info(
                f"[BMC] Regenerating BMC with current idea description (length: {len(current_description)})"
            )
            logger.debug(f"[BMC] Idea description preview: {current_description[:100]}...")
            self._generate()
        else:
            logger.warning(
                "[BMC] No valid idea description found (description is None or empty) - skipping BMC regeneration"
            )

    def update_cost_breakdown(self):
        """
        Use the AI layer to generate a cost structure breakdown and update the cost_structure component.
        """
        logger.info("[BMC] Starting cost structure generation")
        try:
            if hasattr(self._model, "idea") and hasattr(self._model, "ai_layer"):
                description = self._model.idea.description
                logger.debug(
                    f"[BMC] Using idea description for cost structure (length: {len(description)})"
                )
                cost_data = self._cost_structure.generate(self._model.ai_layer, description)
                logger.info("[BMC] Successfully generated cost structure")
                logger.debug(f"[BMC] Cost data: {json.dumps(cost_data, indent=2)}")
                return cost_data
            else:
                logger.warning(
                    "[BMC] Missing required components (Idea or AILayer) for cost structure generation"
                )
                return None
        except Exception as e:
            logger.error(f"[BMC] Failed to generate cost structure: {str(e)}")
            return None

    def _generate(self):
        """
        Internal method to generate BMC content from AI and update components.
        """
        if not hasattr(self._model, "idea"):
            logger.warning("[BMC] Missing 'idea' attribute in model - cannot generate BMC")
            return

        if not hasattr(self._model, "ai_layer"):
            logger.warning("[BMC] Missing 'ai_layer' attribute in model - cannot generate BMC")
            return

        try:
            logger.info("[BMC] Starting BMC generation from AI")
            description = self._model.idea.description

            if not description or not description.strip():
                logger.warning("[BMC] Idea description is empty or None - cannot generate BMC")
                return

            logger.debug(f"[BMC] Using idea description (length: {len(description)})")
            logger.debug(f"[BMC] Idea description preview: {description[:200]}...")

            system_prompt, user_prompt = self._load_prompt_template()
            formatted_user_prompt = user_prompt.replace("{{idea_description}}", description)
            messages = [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": formatted_user_prompt},
            ]

            logger.info("[BMC] Sending prompt to AI layer")
            logger.debug(
                f"[BMC] System prompt length: {len(system_prompt)}, User prompt length: {len(formatted_user_prompt)}"
            )

            # Use rich text generation
            rich_text = self._model.ai_layer.generate_rich_text(messages, format_type="markdown")

            if not rich_text:
                logger.error(
                    "[BMC] No valid BMC content received from AI - generate_rich_text returned None or empty string"
                )
                return

            logger.info(f"[BMC] Successfully generated BMC content (length: {len(rich_text)})")
            logger.debug(f"[BMC] Content preview: {rich_text[:200]}...")

            self.summary = rich_text
            # Store the rich text directly in each component
            components = [
                self._key_partners,
                self._key_activities,
                self._key_resources,
                self._value_propositions,
                self._customer_relationships,
                self._channels,
                self._customer_segments,
                self._cost_structure,
                self._revenue_streams,
            ]

            for component in components:
                component.summary = rich_text

            logger.info("[BMC] Successfully updated all components with generated content")

        except Exception as e:
            import traceback

            logger.error(f"[BMC] Failed to generate BMC from AI: {str(e)}")
            logger.error(f"[BMC] Exception traceback: {traceback.format_exc()}")
            # Don't raise - allow the method to complete, but summary will remain None
