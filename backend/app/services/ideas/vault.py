"""A person's Manifest as an Obsidian-style vault of linked Markdown files (ADR 0005).

``build_vault`` turns their ideas, generated documents, Business Model Canvas sections,
qualification interviews and required skills into files under ``Manifest/``:

- ``Manifest/Home.md``: the map of everything.
- ``Manifest/Ideas/<title>.md``: the idea, links to its documents, skills and related ideas.
- ``Manifest/Documents/<idea>/<document>.md``: each document, linked back to its idea.
- ``Manifest/Skills/<skill>.md``: hubs linking the ideas that need a skill.
- ``Manifest/Interviews/<date> <idea>.md``: qualification interview transcripts.
- ``Manifest/Concepts/<concept>.md``: hubs linking every idea, passage and document that
  mentions a concept (the knowledge graph from ``knowledge_graph.py``, ADR 0006).

Idea notes carry Obsidian block ids (``^p1`` for note sentences, ``^a1`` for interview answers),
and every document line cites the passage it draws on with ``[[<idea>#^p1|↩]]``.

Every file has YAML frontmatter (``manifest_id``, ``type``, ``tags``…) and ``[[wiki-links]]``,
so Obsidian's graph shows how ideas, documents, skills and notes connect. Generated content
sits between ``BEGIN``/``END`` markers; the plugin's ``manifest_vault.py`` replaces only that
block, so anything the person writes outside it survives every sync.
"""

from __future__ import annotations

import hashlib
import json
import re
from datetime import UTC, datetime
from typing import Any

from app.services.ideas import knowledge_graph

ROOT = "Manifest"
# The mark manifest_vault.py writes beside Home.md (Manifest/Assets/); Obsidian resolves the name.
LOGO = "Manifest logo.svg"
BEGIN = "<!-- manifest:begin — generated by Manifest; edits inside this block are replaced on the next sync -->"
END = "<!-- manifest:end -->"
MAX_IDEAS = 200

DOCUMENTS = (
    ("business_model_canvas", "Business Model Canvas"),
    ("pitch_deck", "Pitch Deck"),
    ("product_requirements_document", "Product Requirements"),
    ("provisional_patent", "Provisional Patent Draft"),
    ("similar_ideas", "Similar Ideas"),
)
IDEA_COLUMNS = (
    "idea_id, title, description, created_at, updated_at, is_published, required_skills, "
    + ", ".join(column for column, _ in DOCUMENTS)
)
_UNSAFE = re.compile(r'[\\/:*?"<>|#^\[\]\n\r\t]+')
_WORD = re.compile(r"[a-z][a-z0-9]{2,}")
_STOP = frozenset(
    "the and for with that this from into your their they them are was were will can not "
    "but our you its has have had who what when where which while than then also more most "
    "each every all any per via use using used about over under between across before after".split()
)


def safe_name(text: str, fallback: str = "Untitled") -> str:
    name = _UNSAFE.sub(" ", str(text or "")).strip().strip(".")
    return re.sub(r"\s+", " ", name)[:120] or fallback


def _iso(value: Any) -> str | None:
    if value is None:
        return None
    if isinstance(value, datetime):
        return (value if value.tzinfo else value.replace(tzinfo=UTC)).isoformat()
    return str(value)


def _skills(value: Any) -> list[str]:
    if isinstance(value, str):
        try:
            value = json.loads(value)
        except ValueError:
            value = [part.strip() for part in value.strip("{}").split(",")]
    return [str(s).strip().strip('"') for s in value or [] if str(s).strip()]


def _yaml(meta: dict[str, Any]) -> str:
    lines = ["---"]
    for key, value in meta.items():
        if value is None or value == []:
            continue
        if isinstance(value, list):
            lines.append(f"{key}:")
            lines += [f"  - {json.dumps(item, ensure_ascii=False)}" for item in value]
        elif isinstance(value, bool):
            lines.append(f"{key}: {'true' if value else 'false'}")
        else:
            lines.append(f"{key}: {json.dumps(value, ensure_ascii=False)}")
    return "\n".join([*lines, "---"])


def _file(
    path: str, meta: dict[str, Any], body: str, updated_at: str | None
) -> dict[str, str | None]:
    content = f"{_yaml(meta)}\n{BEGIN}\n{body.strip()}\n{END}\n"
    return {"path": path, "content": content, "updated_at": updated_at}


def _link(path: str, label: str) -> str:
    return f"[[{path.removesuffix('.md')}|{label}]]"


def _tag(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "other"


def _words(idea: dict[str, Any]) -> set[str]:
    text = f"{idea.get('title') or ''} {idea.get('description') or ''}".lower()
    return {w for w in _WORD.findall(text) if w not in _STOP}


def related_ideas(ideas: list[dict[str, Any]], limit: int = 5) -> dict[str, list[str]]:
    """Ideas that share required skills or vocabulary (Jaccard), strongest first."""
    words = {i["idea_id"]: _words(i) for i in ideas}
    skills = {i["idea_id"]: set(_skills(i.get("required_skills"))) for i in ideas}
    related: dict[str, list[str]] = {}
    for idea in ideas:
        a = idea["idea_id"]
        scores = []
        for other in ideas:
            b = other["idea_id"]
            if a == b:
                continue
            union = words[a] | words[b]
            score = (len(words[a] & words[b]) / len(union) if union else 0) + 0.2 * len(
                skills[a] & skills[b]
            )
            if score >= 0.12:
                scores.append((score, b))
        related[a] = [b for _, b in sorted(scores, reverse=True)[:limit]]
    return related


def _note_names(ideas: list[dict[str, Any]]) -> dict[str, str]:
    """File-safe, unique note names per idea (titles may repeat)."""
    names: dict[str, str] = {}
    used: set[str] = set()
    for idea in sorted(ideas, key=lambda i: str(i.get("created_at") or "")):
        base = safe_name(idea.get("title") or "Untitled idea")
        name = base if base.lower() not in used else f"{base} ({str(idea['idea_id'])[:8]})"
        used.add(name.lower())
        names[idea["idea_id"]] = name
    return names


def _short_label(text: str, limit: int = 60) -> str:
    """A file-safe label cut at a word boundary, never mid-word."""
    clean = safe_name(text, "Interview")
    if len(clean) <= limit:
        return clean
    cut = clean[:limit].rsplit(" ", 1)[0]
    return cut if len(cut) >= 20 else clean[:limit]


def _transcript(session: dict[str, Any]) -> str:
    turns = session.get("transcript") or []
    if isinstance(turns, str):
        try:
            turns = json.loads(turns)
        except ValueError:
            turns = []
    lines = []
    for turn in turns:
        who = "Manifest" if turn.get("role") == "assistant" else "Me"
        lines.append(f"**{who}:** {str(turn.get('content') or '').strip()}")
    return "\n\n".join(lines) or "_No answers yet._"


def _canvas_text(idea: dict[str, Any], canvas: list[dict[str, Any]]) -> str | None:
    """The whole canvas (what the app shows); its per-section rows when only those exist."""
    if idea.get("business_model_canvas"):
        return idea["business_model_canvas"]
    filled = [s for s in canvas if s.get("content")]
    if not filled:
        return None
    return "\n\n".join(
        f"## {s['section_name'].replace('_', ' ').title()}\n{s['content'].strip()}" for s in filled
    )


def _document_files(
    idea: dict[str, Any],
    canvas: list[dict[str, Any]],
    name: str,
    idea_file: str,
    updated: str | None,
    cited: dict[str, str] | None = None,
) -> tuple[list[dict[str, str | None]], list[str]]:
    iid = idea["idea_id"]
    title = idea.get("title") or "Untitled idea"
    files, links = [], []
    for column, label in DOCUMENTS:
        text = _canvas_text(idea, canvas) if column == "business_model_canvas" else idea.get(column)
        if not text:
            continue
        text = (cited or {}).get(column) or text
        path = f"{ROOT}/Documents/{name}/{label}.md"
        links.append(f"- {_link(path, label)}")
        files.append(
            _file(
                path,
                {
                    "manifest_id": iid,
                    "type": "document",
                    "document_type": column,
                    "idea": f"[[{idea_file.removesuffix('.md')}|{title}]]",
                    "tags": ["manifest/document", f"manifest/document/{_tag(column)}"],
                    "updated": updated,
                },
                f"# {label}: {title}\n\nPart of {_link(idea_file, title)}. "
                "Draft for the founder to review, not legal, financial or investment advice.\n\n"
                f"{text.strip()}",
                updated,
            )
        )
    return files, links


def idea_graphs(
    ideas: list[dict[str, Any]],
    sections: dict[str, list[dict[str, Any]]],
    interviews: list[dict[str, Any]],
    idea_path: dict[str, str],
) -> dict[str, dict[str, Any]]:
    """The knowledge graph of every idea, cross-linked through the person's other ideas."""
    targets = {iid: path.removesuffix(".md") for iid, path in idea_path.items()}
    graphs = {}
    for idea in ideas:
        iid = idea["idea_id"]
        documents = {
            column: (
                _canvas_text(idea, sections.get(iid) or [])
                if column == "business_model_canvas"
                else idea.get(column)
            )
            or ""
            for column, _ in DOCUMENTS
        }
        graphs[iid] = knowledge_graph.build_graph(
            idea,
            documents,
            knowledge_graph.interview_answers([s for s in interviews if s.get("idea_id") == iid]),
            ideas,
            idea_target=targets[iid],
            idea_targets=targets,
            skills=_skills(idea.get("required_skills")),
        )
    return graphs


def _passage_lines(idea: dict[str, Any], passages: list[dict[str, str]]) -> list[str]:
    """The idea note, one paragraph per sentence so each can carry its block id."""
    note = [p for p in passages if p["kind"] == "note"]
    if not note:
        return [knowledge_graph.plain(idea.get("description")).strip() or "_No description yet._"]
    lines: list[str] = []
    for p in note:
        lines += [f"{p['text']} ^{p['id']}", ""]
    return lines[:-1]


def _concept_file(
    path: str, hub: dict[str, Any], idea_path: dict[str, str], by_id: dict[str, Any]
) -> dict[str, str | None]:
    label = hub["label"]
    ideas_here = {iid for iid, _ in hub["ideas"]}
    body = [f"# {label.title() if label.islower() else label}", ""]
    first = hub["ideas"][0][1] if hub["ideas"] else {}
    if first.get("role_label"):
        body += [f"**{first['role_label']}** · {first.get('why', '')}".rstrip(" ·"), ""]
    body += ["Concept in your ideas. Every link below mentions it.", "", "## Ideas"]
    for iid, concept in hub["ideas"]:
        target = idea_path[iid].removesuffix(".md")
        cites = " ".join(f"[[{target}#^{pid}|^{pid}]]" for pid in concept["passages"][:8])
        title = by_id[iid].get("title") or "Untitled idea"
        body.append(f"- {_link(idea_path[iid], title)}" + (f" — {cites}" if cites else ""))
        names = dict(DOCUMENTS)
        for doc in concept["documents"]:
            doc_path = f"{ROOT}/Documents/{target.rsplit('/', 1)[-1]}/{names[doc]}.md"
            body.append(f"  - {_link(doc_path, names[doc])}")
    also = sorted({o for _, c in hub["ideas"] for o in c["ideas"]} - ideas_here)
    if also:
        body += ["", "## Also mentioned in"]
        body += [f"- {_link(idea_path[o], by_id[o].get('title') or 'Untitled idea')}" for o in also]
    return _file(
        f"{path}.md",
        {"type": "concept", "tags": ["manifest/concept"], "ideas": len(ideas_here | set(also))},
        "\n".join(body),
        None,
    )


def _idea_body(
    idea: dict[str, Any],
    graph: dict[str, Any],
    doc_links: list[str],
    skills: list[str],
    similar: list[str],
    idea_path: dict[str, str],
    by_id: dict[str, Any],
) -> list[str]:
    """The idea note: sentences with block ids, interview answers, documents, concepts,
    skills and related ideas (by shared concepts first, then by shared vocabulary)."""
    title = idea.get("title") or "Untitled idea"
    body = [f"# {title}", "", *_passage_lines(idea, graph["passages"])]
    answers = [p for p in graph["passages"] if p["kind"] == "answer"]
    if answers:
        body += ["", "## In my words (interviews)", ""]
        body += [f"- {p['text']} ^{p['id']}" for p in answers]
    body += ["", "## Documents", *(doc_links or ["_None yet. Ask your agent to write them._"])]
    if graph["concepts"]:
        # The idea model (ADR 0009): concepts grouped by the role they play.
        body += ["", "## Concepts"]
        for role in knowledge_graph.ROLES:
            group = [c for c in graph["concepts"] if c.get("role", "context") == role]
            if not group:
                continue
            body += ["", f"**{knowledge_graph.ROLE_LABELS[role]}**"]
            body += [
                f"- {_link(c['path'] + '.md', c['label'])}"
                + (f" (in {c['parent']})" if c.get("parent") else "")
                + (f" · {len(c['ideas'])} other ideas" if c["ideas"] else "")
                for c in group
            ]
    if graph.get("relations"):
        body += ["", "## How it connects"]
        target = idea_path[idea["idea_id"]].removesuffix(".md")
        body += [
            f"- {r['source']} → {r['label']} → {r['target']} "
            + " ".join(f"[[{target}#^{pid}|^{pid}]]" for pid in r["passages"][:3])
            for r in graph["relations"]
        ]
    if skills:
        body += [
            "",
            "## Skills needed",
            *[f"- {_link(f'{ROOT}/Skills/{safe_name(s)}.md', s)}" for s in skills],
        ]
    connected = [(r["idea_id"], r["concepts"]) for r in graph["related"]]
    connected += [(r, []) for r in similar if r not in dict(connected)]
    if connected:
        body += ["", "## Related ideas"]
        body += [
            f"- {_link(idea_path[r], by_id[r].get('title') or 'Untitled idea')}"
            + (
                " — shares "
                + ", ".join(_link(knowledge_graph.concept_path(c) + ".md", c) for c in shared[:6])
                if shared
                else ""
            )
            for r, shared in connected
        ]
    return body


# Files that only change when an idea, its canvas or an interview changes; hubs and Home are
# always sent (they are small and the client skips unchanged files).
_PER_IDEA = (f"{ROOT}/Ideas/", f"{ROOT}/Documents/", f"{ROOT}/Interviews/")


def _changed_since(
    ideas: list[dict[str, Any]],
    sections: dict[str, list[dict[str, Any]]],
    interviews: list[dict[str, Any]],
    since: str,
) -> bool:
    stamps = [_iso(i.get("updated_at")) or _iso(i.get("created_at")) for i in ideas]
    stamps += [_iso(s.get("updated_at")) or _iso(s.get("created_at")) for s in interviews]
    stamps += [_iso(r.get("updated_at")) for rows in sections.values() for r in rows]
    return any(stamp and stamp >= since for stamp in stamps)


def build_files(
    ideas: list[dict[str, Any]],
    sections: dict[str, list[dict[str, Any]]],
    interviews: list[dict[str, Any]],
    *,
    since: str | None = None,
    site: str = "https://manifeststartup.com",
) -> list[dict[str, str | None]]:
    """Pure function: rows in, vault files out (tested without a database).

    With ``since``, everything is sent when anything changed after it (ideas link to each
    other through related ideas and shared concepts, so one edit can change every note), and
    only the hubs and Home when nothing did.
    """
    files = _all_files(ideas, sections, interviews, site)
    if since and not _changed_since(ideas, sections, interviews, since):
        files = [f for f in files if not str(f["path"]).startswith(_PER_IDEA)]
    return files


def all_paths(files: list[dict[str, str | None]]) -> list[str]:
    return sorted(str(f["path"]) for f in files)


def _all_files(
    ideas: list[dict[str, Any]],
    sections: dict[str, list[dict[str, Any]]],
    interviews: list[dict[str, Any]],
    site: str,
) -> list[dict[str, str | None]]:
    names = _note_names(ideas)
    related = related_ideas(ideas)
    by_id = {i["idea_id"]: i for i in ideas}
    idea_path = {iid: f"{ROOT}/Ideas/{name}.md" for iid, name in names.items()}
    files: list[dict[str, str | None]] = []
    skill_ideas: dict[str, list[str]] = {}
    graphs = idea_graphs(ideas, sections, interviews, idea_path)
    concept_hubs: dict[str, dict[str, Any]] = {}

    for idea in ideas:
        iid = idea["idea_id"]
        title = idea.get("title") or "Untitled idea"
        updated = _iso(idea.get("updated_at")) or _iso(idea.get("created_at"))
        # New interview answers change the idea note and its citations too.
        updated = (
            max(
                [
                    updated or "",
                    *(
                        _iso(i.get("updated_at")) or ""
                        for i in interviews
                        if i.get("idea_id") == iid
                    ),
                ]
            )
            or None
        )
        skills = _skills(idea.get("required_skills"))
        for skill in skills:
            skill_ideas.setdefault(skill, []).append(iid)
        graph = graphs[iid]
        for concept in graph["concepts"]:
            hub = concept_hubs.setdefault(concept["path"], {"label": concept["label"], "ideas": []})
            hub["ideas"].append((iid, concept))
        doc_files, doc_links = _document_files(
            idea,
            sections.get(iid) or [],
            names[iid],
            idea_path[iid],
            updated,
            graph["documents"],
        )
        files += doc_files
        body = _idea_body(idea, graph, doc_links, skills, related.get(iid, []), idea_path, by_id)
        body += ["", f"[Open in Manifest]({site}/ideas/{iid})"]
        files.append(
            _file(
                idea_path[iid],
                {
                    "manifest_id": iid,
                    "type": "idea",
                    "title": title,
                    "published": bool(idea.get("is_published")),
                    "created": _iso(idea.get("created_at")),
                    "updated": updated,
                    "skills": skills,
                    "tags": ["manifest/idea", *[f"skill/{_tag(s)}" for s in skills]],
                    "url": f"{site}/ideas/{iid}",
                },
                "\n".join(body),
                updated,
            )
        )

    for session in interviews:
        iid = session.get("idea_id")
        created = _iso(session.get("created_at")) or ""
        updated = _iso(session.get("updated_at")) or created
        label = _short_label(session.get("initial_idea_text") or "Interview")
        path = f"{ROOT}/Interviews/{created[:10]} {label}.md"
        idea_line = (
            f"About {_link(idea_path[iid], by_id[iid].get('title') or 'idea')}.\n\n"
            if iid in idea_path
            else ""
        )
        score = session.get("qualification_score")
        verdict = (
            f"\n\n## Verdict\nScore: {score}/100. {session.get('qualification_explanation') or ''}"
            if score is not None
            else ""
        )
        files.append(
            _file(
                path,
                {
                    "manifest_id": session.get("id"),
                    "type": "interview",
                    "status": session.get("status"),
                    "idea": f"[[{idea_path[iid].removesuffix('.md')}]]"
                    if iid in idea_path
                    else None,
                    "tags": ["manifest/interview"],
                    "created": created,
                },
                f"# Qualification interview: {label}\n\n{idea_line}> {session.get('initial_idea_text') or ''}\n\n"
                f"{_transcript(session)}{verdict}",
                updated,
            )
        )

    for skill, idea_ids in sorted(skill_ideas.items()):
        files.append(
            _file(
                f"{ROOT}/Skills/{safe_name(skill)}.md",
                {"type": "skill", "tags": ["manifest/skill"]},
                f"# {skill}\n\nIdeas that need this skill:\n\n"
                + "\n".join(
                    f"- {_link(idea_path[i], by_id[i].get('title') or 'Untitled idea')}"
                    for i in idea_ids
                ),
                None,
            )
        )

    for path, hub in sorted(concept_hubs.items()):
        files.append(_concept_file(path, hub, idea_path, by_id))

    count = len(ideas)
    home = [
        f"![[{LOGO}|72]]",
        "",
        "# Manifest",
        "",
        "Your ideas, plans and notes. Open Graph view to see how they connect.",
        "",
        f"> [!manifest] {count} idea{'' if count == 1 else 's'} · synced with "
        f"[manifeststartup.com]({site}/ideas)",
        "",
        "## Ideas",
        *[f"- {_link(idea_path[i['idea_id']], i.get('title') or 'Untitled idea')}" for i in ideas],
    ]
    if skill_ideas:
        home += [
            "",
            "## Skills",
            *[f"- {_link(f'{ROOT}/Skills/{safe_name(s)}.md', s)}" for s in sorted(skill_ideas)],
        ]
    if concept_hubs:
        top = sorted(concept_hubs.items(), key=lambda kv: (-len(kv[1]["ideas"]), kv[0]))[:40]
        home += [
            "",
            "## Concepts",
            ", ".join(_link(f"{path}.md", hub["label"]) for path, hub in top),
        ]
    home += [
        "",
        "## Notes",
        "Your own notes live in `Notes/` and link to ideas with [[wiki-links]].",
    ]
    files.append(
        _file(
            f"{ROOT}/Home.md",
            {"type": "home", "tags": ["manifest"], "cssclasses": ["manifest-home"]},
            "\n".join(home),
            None,
        )
    )
    return files


def fingerprint(
    ideas: list[dict[str, Any]],
    sections: dict[str, list[dict[str, Any]]],
    interviews: list[dict[str, Any]],
) -> str:
    """Changes whenever an idea, canvas section or interview is added, edited or deleted."""
    parts = [f"i:{i['idea_id']}:{_iso(i.get('updated_at'))}" for i in ideas]
    parts += [
        f"s:{iid}:{r.get('section_name')}:{_iso(r.get('updated_at'))}"
        for iid, rows in sections.items()
        for r in rows
    ]
    parts += [f"q:{s.get('id')}:{_iso(s.get('updated_at'))}" for s in interviews]
    return hashlib.sha256("\n".join(sorted(parts)).encode()).hexdigest()[:32]


def build_vault(
    db: Any, user_id: str, since: str | None = None, known_fingerprint: str | None = None
) -> dict[str, Any]:
    """Load the person's own ideas, canvas sections and interviews, and build the files."""
    ideas = (
        db.table("ideas")
        .select(IDEA_COLUMNS)
        .eq("user_id", user_id)
        .order("created_at", desc=True)
        .limit(MAX_IDEAS)
        .execute()
        .data
        or []
    )
    sections: dict[str, list[dict[str, Any]]] = {}
    for idea in ideas:
        rows = (
            db.table("business_model_canvas_sections")
            .select("section_name, content, updated_at")
            .eq("idea_id", idea["idea_id"])
            .execute()
            .data
            or []
        )
        sections[idea["idea_id"]] = rows
    interviews = (
        db.table("idea_qualification_sessions")
        .select(
            "id, idea_id, initial_idea_text, status, transcript, qualification_score, "
            "qualification_explanation, created_at, updated_at"
        )
        .eq("user_id", user_id)
        .order("created_at", desc=True)
        .limit(MAX_IDEAS)
        .execute()
        .data
        or []
    )
    for idea in ideas:
        idea["idea_id"] = str(idea["idea_id"])
    for session in interviews:
        session["idea_id"] = str(session["idea_id"]) if session.get("idea_id") else None
    stamp = fingerprint(ideas, sections, interviews)
    if since and known_fingerprint and known_fingerprint == stamp:
        # Nothing was added, changed or deleted: skip building the graph entirely.
        return {
            "generated_at": datetime.now(UTC).isoformat(),
            "root": ROOT,
            "idea_count": len(ideas),
            "files": [],
            "paths": [],
            "fingerprint": stamp,
        }
    everything = _all_files(ideas, sections, interviews, "https://manifeststartup.com")
    files = everything
    # A known fingerprint that differs means something changed, a deletion included (which
    # leaves no timestamp behind), so everything is sent.
    if since and not known_fingerprint and not _changed_since(ideas, sections, interviews, since):
        files = [f for f in everything if not str(f["path"]).startswith(_PER_IDEA)]
    return {
        "generated_at": datetime.now(UTC).isoformat(),
        "root": ROOT,
        "idea_count": len(ideas),
        "files": files,
        # Every Manifest/ file that exists now, so a vault can tidy away notes for ideas
        # that were renamed or deleted (and the concepts only they mentioned).
        "paths": all_paths(everything),
        "fingerprint": stamp,
    }


def idea_knowledge_graph(db: Any, user_id: str, idea_id: str) -> dict[str, Any] | None:
    """The knowledge graph of one of the person's own ideas, cited documents included.

    Owner only: the graph links the person's other ideas, which collaborators can't see.
    Built live from the note, interviews and documents, so it grows with every interview
    answer and every generated document without any stored state.
    """
    idea = (
        db.table("ideas")
        .select(IDEA_COLUMNS)
        .eq("idea_id", idea_id)
        .eq("user_id", user_id)
        .limit(1)
        .execute()
        .data
        or [None]
    )[0]
    if not idea:
        return None
    others = (
        db.table("ideas")
        .select("idea_id, title, description, created_at, required_skills")
        .eq("user_id", user_id)
        .order("created_at", desc=True)
        .limit(MAX_IDEAS)
        .execute()
        .data
        or []
    )
    sections = (
        db.table("business_model_canvas_sections")
        .select("section_name, content")
        .eq("idea_id", idea_id)
        .execute()
        .data
        or []
    )
    sessions = (
        db.table("idea_qualification_sessions")
        .select("idea_id, initial_idea_text, transcript, created_at")
        .eq("user_id", user_id)
        .eq("idea_id", idea_id)
        .execute()
        .data
        or []
    )
    idea["idea_id"] = str(idea["idea_id"])
    everyone = [{**o, "idea_id": str(o["idea_id"])} for o in others]
    if not any(o["idea_id"] == idea["idea_id"] for o in everyone):
        everyone.append(idea)
    names = _note_names(everyone)
    targets = {iid: f"{ROOT}/Ideas/{name}" for iid, name in names.items()}
    documents = {
        column: (
            _canvas_text(idea, sections) if column == "business_model_canvas" else idea.get(column)
        )
        or ""
        for column, _ in DOCUMENTS
    }
    graph = knowledge_graph.build_graph(
        idea,
        documents,
        knowledge_graph.interview_answers(sessions),
        everyone,
        idea_target=targets[idea["idea_id"]],
        idea_targets=targets,
        skills=_skills(idea.get("required_skills")),
    )
    titles = {o["idea_id"]: o.get("title") or "Untitled idea" for o in everyone}
    graph["idea_id"] = idea["idea_id"]
    graph["titles"] = titles
    graph["targets"] = targets
    return graph
